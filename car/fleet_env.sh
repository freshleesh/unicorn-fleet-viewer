# Source AFTER unicorn.sh. Puts this car's stack on its own localhost-only ROS domain
# and lets the fleet relay reach the shared domain (1) over Wi-Fi.
#   nuc1 -> 11, nuc4 -> 14, nuc5 -> 15  (private, lo only)     shared = 1 (Wi-Fi)
# Car = hostname (override FLEET_CAR=). Wi-Fi interface found automatically (override FLEET_IFACE=).
export FLEET_CAR=${FLEET_CAR:-$(hostname)}
export FLEET_SHARED=1
case "$FLEET_CAR" in
    nuc1) FLEET_PRIVATE=11; FLEET_COLOR=1,0.4,0.1 ;;
    nuc4) FLEET_PRIVATE=14; FLEET_COLOR=0.2,0.6,1 ;;
    nuc5) FLEET_PRIVATE=15; FLEET_COLOR=0.3,1,0.3 ;;
    *)    echo "fleet_env: unknown car $FLEET_CAR (add it here and to FLEET in fleet_relay.py)" >&2; return 1 ;;
esac
export FLEET_PRIVATE FLEET_COLOR
if [ -z "$FLEET_IFACE" ]; then
    for _d in /sys/class/net/*/wireless; do FLEET_IFACE=$(basename "$(dirname "$_d")"); break; done
fi
[ -n "$FLEET_IFACE" ] || { echo "fleet_env: no Wi-Fi interface found; set FLEET_IFACE" >&2; return 1; }
export FLEET_IFACE
mkdir -p ~/.ros
_xml=$HOME/.ros/cyclonedds_fleet_car.xml
cat > $_xml.$$ <<XML
<?xml version="1.0" encoding="UTF-8" ?>
<!-- generated by car/fleet_env.sh -->
<CycloneDDS xmlns="https://cdds.io/config">
  <Domain id="$FLEET_PRIVATE">
    <General>
      <Interfaces><NetworkInterface address="127.0.0.1" multicast="true"/></Interfaces>
    </General>
    <Discovery><ParticipantIndex>none</ParticipantIndex></Discovery>
  </Domain>
  <Domain id="$FLEET_SHARED">
    <General>
      <Interfaces><NetworkInterface name="$FLEET_IFACE" multicast="default"/></Interfaces>
      <AllowMulticast>spdp</AllowMulticast>
    </General>
    <Discovery><ParticipantIndex>none</ParticipantIndex></Discovery>
  </Domain>
</CycloneDDS>
XML
cmp -s $_xml.$$ $_xml 2>/dev/null && rm $_xml.$$ || { mv $_xml.$$ $_xml; sync; }   # per-PID temp: several scripts start at once
export CYCLONEDDS_URI=file://$_xml
export ROS_DOMAIN_ID=$FLEET_PRIVATE
unset ROS_AUTOMATIC_DISCOVERY_RANGE
